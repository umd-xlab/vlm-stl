import math
import threading
import sys
import rtamt
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

class Monitor:
    def __init__(self, feed, rule_line, stop_event):
        """
        The heart of the run time assurance (rta)
        Many instances (num = # of rules) booted up in parallel inside booter.py

        Responsible for monitoring the feed for robot_states that match its rule
        Feeds matching states through update function which generates robustness values
        Robustness values then get sent to log files (failure_log and/or data_dump_log)
        Robustness values also synchronosouly plotted in plots folder

        Evalutes one STL rule against the shared feed

        feed - shared StateFeed
        rule_line - (string), to be popualted in add_rule function, contains the stl rule
        input - (string), to be populated in add_rule function, contains input variables for rule
        output - (string), to be populated in add_rule function, contains output variables for rule
        spec - (rtamt object), used to pass in rule instantiation and updates into rtamt library
        stop_event - internal variable, used for threading, signal to stop running
        fig and graph - just variable substitutes for the typical fig,ax schema, need to make subplots to be able to save graph
        rule_data - (tuple of lists) containing the time and output robustness value for the rule, appended to every time new output is generated by rtamt
        state_data - (dictionary of tuple of lists) ex: {'spd' : ([1,2,3],[4,5,6])} each tuple contains time and signal respectively for each state variable
            used by rule. To be plotted on graphs to help with output robustness analysis
        failures - list of rule violations stored in memory
        robustness_results - list of all robustness outputs stored in memory

        """
        self.feed = feed
        self.rule = None
        self.input = None
        self.output = None
        self.spec = None
        self.stop_event = stop_event

        self.fig, self.graph = None, None
        self.rule_data = ([],[]) # tuple containing x and y values of generated rule robustness
        self.state_data = {} #dictionary containing state datapoints for each variable
        self.waypoint_times = {}

        self.failures = []
        self.robustness_results = []

        self.add_rule(rule_line)
        self.instantiate_rule()
        self.instantiate_state_data()


    def add_rule(self, line: list):
        """
        Passed through with rule_line variable in init
        line - (list of strings), sent over by booter.py, contains 3 columns for "rule", "input" varibale, and "output" variable

        Indexes into list extracting comonents and setting them to variables, creates empty rtamt instance
        """
        self.rule = line[0]
        self.input = line[1]
        if self.input == "":
            self.input = None
        self.output = line[2]
        if self.output == "":
            self.output = None
        self.spec = rtamt.StlDenseTimeSpecification(semantics=rtamt.Semantics.OUTPUT_ROBUSTNESS) #defualt is standard robustness

    def instantiate_rule(self):
        """
        Uses values extracted in add_rule function to set propper parameters
        Then calls standard rtamt functions of parse and pastify to activate rule

        NOTE: pastify is needed to evaluate future timed temporal operators such as "eventually"

        """
        self.spec.declare_var('out', 'float')
        if self.input is not None:
            self.spec.declare_var(str(self.input), 'float')
            self.spec.set_var_io_type(str(self.input), 'input')
        if self.output is not None:
            self.spec.declare_var(str(self.output), 'float')
            self.spec.set_var_io_type(str(self.output), 'output')

        self.spec.spec = self.rule.strip("'") #removes excess single quotes (') from rule

        try:
            self.spec.parse()
            self.spec.pastify()
        except rtamt.RTAMTException as err:
            raise RuntimeError(f"Failed to initialize STL rule: {self.rule}") from err
    
    def instantiate_state_data(self):
        """
        Creates empty dictionary of variable states to be plotted on graphs

        """
        for var in [self.input, self.output]:
            if var is not None:
                self.state_data[var] = ([],[])


    def update(self, state):
        """
        Proccesses a single State observation

        Determines what variables (that exist in this rule) are reported in this new line of data.
        Not all states reported in every line, therefore checks which variables are actually populated
        If any of those variables are populated, extracts their data and appends their values to their respective state data and update instance
        Sends the update instance through the rtamt library
        Upon receiving the output from the rtamt library, if new output robustness values reported, stores in robustness_results
        """
        vars_to_update = []
        #Determines which variables are populated
        for var in [self.input, self.output]:
            if var is not None:
                value = state.variables.get(var)

                if value is not None and not math.isnan(float(value)):
                    vars_to_update.append(var)

        if not vars_to_update:
            return
        
        updates = []
        #Updates the variable states dictionary and prepares update message for rtamt
        for var in vars_to_update:
            self.waypoint_times[float(state.time)] = state.waypoint_index
            time = float(state.time)
            signal = float(state.variables[var])
            self.state_data[var][0].append(time)
            self.state_data[var][1].append(signal)
            updates.append([var, [[time, signal]]])

        #send the update message into rtamt and receives output
        rob = self.spec.update(*updates)

        #Upon reception, rob will be a list of lists ex: [[5.4, inf], [6.1, -0.7]]
        #List is looped, rule_data points updated, calls update function for graphs
        for result in rob:
            self.route_data(result)
            self.rule_data[0].append(result[0])
            self.rule_data[1].append(result[1])

    def route_data(self, output):
        """
        Called from the update function, responsible for storing robusntess in memory

        Determines whether the output robustness value represents a violation
        """
        time = float(output[0])
        robustness = float(output[1])

        result = {"rule": self.rule, "time": time, "waypoint_index": self.waypoint_times.get(time), "robustness":robustness}

        self.robustness_results.append(result)
        if robustness < 0:
            self.failures.append(result)

    def update_graph(self):
        """
        Old Version Idea to use for online: Call after every update, clear current graphs and repopulate.

        Currently just offline:
        Updates graph with the stored signal and robustness data at the end of evaluation
        """
        if self.fig is None:
            self.fig, self.graph = plt.subplots()

        self.graph.clear()

        #Step functions, to accurately represent the assumption of constant signal until reported otherwise
        self.graph.step(*self.rule_data, where='post', label = 'Rule Output Robustness')
        for var in self.state_data:
            #Loads in rule variables state data to assist with validation
            self.graph.step(*self.state_data[var], where='post', label = f'{var}', alpha=0.5)

        #Shading logic, used to represent the infinities given by output robustness (aka when a rule is vacously true)
        start_shading = None
        for (x,y) in zip(self.rule_data[0], self.rule_data[1]):
            if y == float('inf') and start_shading is None:
                start_shading = x
            elif y != float('inf') and start_shading is not None:
                self.graph.axvspan(start_shading, x, color='gray', alpha=0.25)
                start_shading = None

        if start_shading is not None and self.rule_data[0]:
            self.graph.axvspan(start_shading, self.rule_data[0][-1], color='gray', alpha=0.25)

        #Includes grid, title, legend, and centers the graph
        self.graph.grid(True, which='both')
        self.graph.set_title(f"Rule: {self.rule}", wrap=True)
        self.graph.axhline(y=0, color='k')
        self.graph.axvline(x=0, color='k')
        self.graph.legend()
        plt.tight_layout()


    def activate(self):
        """
        Activation function, called from booter.py by each thread to start the observer

        Continuosly monitors the shared StateFeed
        Each monitor maintains its own read index so that every observation is processed exactly once
        When the feed is marked completed, all remaining observations are processed before termination
        """
        next_state_index = 0
        while True:
            with self.feed.condition:
                self.feed.condition.wait_for(lambda: next_state_index < len(self.feed.states) or self.feed.completed or self.stop_event.is_set())

                if self.stop_event.is_set():
                    return
                
                new_states = self.feed.states[next_state_index:]
                next_state_index += len(new_states)

                completed = self.feed.completed
            
            for state in new_states:
                if self.stop_event.is_set():
                    return
                self.update(state)

            if completed:
                return